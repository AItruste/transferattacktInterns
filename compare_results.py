#!/usr/bin/env python3
"""Compare reproduced results against provided baseline."""
import pandas as pd

print("=" * 60)
print("OVERALL ATTACK SUMMARY COMPARISON")
print("=" * 60)
orig = pd.read_csv("results_baseline/subset_attack_summary.csv")
repro = pd.read_csv("results_reproduced/subset_attack_summary.csv")
print("\n--- Original ---")
print(orig.to_string(index=False))
print("\n--- Reproduced ---")
print(repro.to_string(index=False))
match1 = orig.round(10).equals(repro.round(10))
print(f"\nExact match: {match1}")

print("\n" + "=" * 60)
print("SUMMARY BY GOAL COMPARISON")
print("=" * 60)
orig2 = pd.read_csv("results_baseline/subset_attack_summary_by_goal.csv")
repro2 = pd.read_csv("results_reproduced/subset_attack_summary_by_goal.csv")
print("\n--- Original ---")
print(orig2.to_string(index=False))
print("\n--- Reproduced ---")
print(repro2.to_string(index=False))
match2 = orig2.round(10).equals(repro2.round(10))
print(f"\nExact match: {match2}")

print("\n" + "=" * 60)
print("ATTACKER-VICTIM SUMMARY COMPARISON")
print("=" * 60)
orig3 = pd.read_csv("results_baseline/subset_attacker_victim_summary.csv")
repro3 = pd.read_csv("results_reproduced/subset_attacker_victim_summary.csv")
print(f"Rows: orig={len(orig3)}, repro={len(repro3)}")
match3 = orig3.round(10).equals(repro3.round(10))
print(f"Exact match: {match3}")

print("\n" + "=" * 60)
print("EVAL LONG CSV COMPARISON")
print("=" * 60)
orig4 = pd.read_csv("results_baseline/subset_attack_eval_long.csv")
repro4 = pd.read_csv("results_reproduced/subset_attack_eval_long.csv")
print(f"Rows: orig={len(orig4)}, repro={len(repro4)}")
match4 = orig4.round(10).equals(repro4.round(10))
print(f"Exact match: {match4}")

print("\n" + "=" * 60)
print("RAW SIMILARITIES COMPARISON")
print("=" * 60)
orig5 = pd.read_csv("results_baseline/subset_raw_similarities_long.csv")
repro5 = pd.read_csv("results_reproduced/subset_raw_similarities_long.csv")
print(f"Rows: orig={len(orig5)}, repro={len(repro5)}")
match5 = orig5.round(10).equals(repro5.round(10))
print(f"Exact match: {match5}")

print("\n" + "=" * 60)
print("FINAL VERDICT")
print("=" * 60)
all_match = all([match1, match2, match3, match4, match5])
if all_match:
    print("ALL FILES MATCH PERFECTLY - Baseline reproduction CONFIRMED!")
else:
    print("Some files differ. Check individual results above.")
    if not match1: print("  - subset_attack_summary.csv DIFFERS")
    if not match2: print("  - subset_attack_summary_by_goal.csv DIFFERS")
    if not match3: print("  - subset_attacker_victim_summary.csv DIFFERS")
    if not match4: print("  - subset_attack_eval_long.csv DIFFERS")
    if not match5: print("  - subset_raw_similarities_long.csv DIFFERS")
